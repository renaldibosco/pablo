const isPi = (b) => b.family === 'rpi';
const usbBoard = (b) => !isPi(b);

const adcCount = (b) => b.pins.filter((p) => p.t === 'io' && !p.alias && p.caps.includes('adc')).length;
const hasWifi = (b) => !!(b.wireless && b.wireless.wifi);
